import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const base = 'http://127.0.0.1:3001';
const initial = await fetch(base + '/api/state');
const cookie = initial.headers.get('set-cookie').split(';')[0];
const post = async (path, body = {}, extraHeaders = {}) => {
  const response = await fetch(base + path, { method: 'POST', headers: { 'Content-Type': 'application/json', cookie, ...extraHeaders }, body: JSON.stringify(body) });
  return { status: response.status, body: await response.json() };
};
const entered = await post('/api/live/enter');
assert.equal(entered.status, 200);
assert.equal(entered.body.chain.live, true);
assert.equal(entered.body.world.inventory.every(g => ['DP-0042','R-042'].includes(g.id)), true);
const prior = entered.body.world, requestId = 'production-api-smoke-ammo-v1';
const repeated = entered.body.chain.receipts.some(r => r.id === requestId + ':service-payment');
const paid = await post('/api/action', { type: 'ammo', requestId });
assert.equal(paid.status, 200);
assert.equal(paid.body.chain.pending, false, paid.body.chain.error);
assert.equal(paid.body.world.ammo, prior.ammo + (repeated ? 0 : 60));
assert.equal(paid.body.world.cash, prior.cash - (repeated ? 0 : 90));
const duplicate = await post('/api/action', { type: 'ammo', requestId });
assert.equal(duplicate.status, 200);
assert.equal(duplicate.body.world.ammo, paid.body.world.ammo);
assert.equal(duplicate.body.world.cash, paid.body.world.cash);
const hostileOrigin = await post('/api/action', { type: 'ammo', requestId: 'must-not-sign' }, { Origin: 'https://unrelated.invalid' });
assert.equal(hostileOrigin.status, 403);
const forged = await post('/api/action', { type: 'settle', requestId: 'must-not-award', success: true, cash: 999999, recovered: ['R-042'] });
assert.equal(forged.status, 400);
const outsider = await fetch(base + '/api/state');
const otherCookie = outsider.headers.get('set-cookie').split(';')[0];
const stolen = await fetch(base + '/api/live/enter', { method: 'POST', headers: { cookie: otherCookie } });
assert.equal(stolen.status, 400);
const latest = await (await fetch(base + '/api/state', { headers: { cookie } })).json();
assert.equal(latest.world.cash, paid.body.world.cash);
const result = { status: 'verified', kind: 'compiled production HTTP service and real testnet credit payment', verifiedAt: new Date().toISOString(), contractId: latest.chain.contractId, accountId: latest.chain.accountId, ammo: latest.world.ammo, credits: latest.world.cash, checks: ['registered inventory projection', 'confirmed 90-credit ammunition payment', 'duplicate command idempotency', 'cross-origin command rejected', 'forged extraction/reward rejected', 'exclusive pilot lease'], transaction: latest.chain.receipts.find(r => r.id === requestId + ':service-payment') };
await writeFile('docs/PRODUCTION_API_VERIFIED.json', JSON.stringify(result, null, 2) + '\n');
assert.equal((await post('/api/live/exit')).status, 200);
console.log('Production API verified: real testnet payment, one ammo award, no duplicate debit, no forged rewards, no pilot lease theft.');
